#include <stdio.h>


// อะไรคือ \0
int main() {

    // 1. ข้อความปกติ banana มีหกตัว แต่ต้องประกาศกินที่ไป 7 เพราะต้องเผื่อ '\0' ไว้ด้วย เพราะภาษา C ถ้าเป็น sentence(ประโยค ก็คือมี "")
    // ระบบจะใส่ '\0' เองปิดให้เสมอ
    /*
        ข้อสังเกตง่าย ๆ เวลาเขียนโค้ด

        • ถ้าใช้ ' ' (Single Quote) เช่น 'A', 'b', '5'  มันคืออักขระตัวเดียว ไม่มี '\0'
        • ถ้าใช้ " " (Double Quote) เช่น "A", "hello"  มันคือข้อความ ต้องมี '\0' พ่วงท้าย

    */

    //ตัวอย่างที่ผิด รันแล้วจะขึ้นตัวอักษรแปลกๆ
    char badWord[6] = "banana";
    printf("result 2: %s\n", badWord);

    //1. ตัวอย่างที่ถูก
    char word[7] = "banana";

    // 2. การทำงานของฟังชั่น printf ที่ใช้ %s มันก็จะลูปแสดงตัวอักษร char ไปเรื่อยๆ ทีละตัว
    printf("result 1: %s\n", word);
    // หน้าจอจะขึ้น: banana

    // 3. แอบเอา '\0' ไปใส่ตรงช่องที่ 3 (แทนที่ตัว 'a' ตัวที่สอง)
    word[3] = '\0';

    // 4. การทำงานของฟังชั่น printf ที่ใช้ %s มันก็จะลูปแสดงตัวอักษร char ไปเรื่อยๆ ทีละตัว แต่พอเจอ \0 มันก็จะหยุดการลูป
    printf("result 2: %s\n", word);
    // หน้าจอจะขึ้น: ban

    /*
        ดัชนี (Index)	0	1	2	3	4	5	6
        ตัวอักษรเดิม	'b'	'a'	'n'	'a'	'n'	'a'	'\0'
        พอใส่ word[3] = '\0'	'b'	'a'	'n'	'\0'	'n'	'a'	'\0'
    */



    return 0;
}
